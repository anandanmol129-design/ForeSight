def available(recs):
    """The plan shows whenever the synthetic list or the real-data rules produced an action."""
    return bool(recs)


def _with_temp(rec):
    """Add the derived temperature row for every power row (the 2nd-order chain power → heat)."""
    k = rec.get("c_per_kw", C_PER_KW)
    out = list(rec["changes"])
    for c in rec["changes"]:
        if c["resource"] == "power_kw" and c.get("level") and c.get("heat", True):
            out.append({"rack": c["rack"], "resource": "temp_c", "order": 2,
                        "level": k * c["level"],
                        "note": f"from {c['level']:+.2f} kW at {k:.2f} °C/kW"})
    return out


def _state(r):
    """Live (level, slope/week, capacity, margin) of one forecast result."""
    return (r["fc"]["last_level"], 7 * r["fc"]["slope"], r["capacity"],
            r["capacity"] - r["threshold"])


def _days_to_safe(level, slope_wk, safe):
    """Linear what-if in model days; None = not within the horizon."""
    if level >= safe:
        return 0.0
    if slope_wk <= 1e-9:
        return None
    d = 7 * (safe - level) / slope_wk
    return d if d <= config.HORIZON_DAYS else None


def _row(by_key, rack, res, deltas, rec_ids, unit_days=7):
    """Before/after for one rack × resource given summed deltas. Weeks are in the display unit
    (unit_days model days each: 7 = weeks, 1 = hours on an hourly record)."""
    level, slope, cap, margin = _state(by_key[(rack, res)])
    lv, sl, cp = level + deltas["level"], slope + deltas["slope"], cap + deltas["capacity"]
    after_d = _days_to_safe(lv, sl, cp - margin)           # what-if: linear projection
    likely = by_key[(rack, res)]["eta"]["likely"]          # now: the engine's own P50 ETA
    verdict = ("over" if lv >= cp - margin else
               "tight" if (after_d is not None and after_d < 7 * config.WARNING_WEEKS)
               or lv >= cp - margin - 0.05 * cp else "ok")
    return {"rack": rack, "resource": res, "unit": config.UNITS.get(res, ""),
            "before": level, "after": lv, "peak": lv + deltas["temporary"],
            "capacity_before": cap, "capacity_after": cp,
            "safe_before": cap - margin, "safe_after": cp - margin,
            "weeks_before": round(likely / unit_days, 1) if likely is not None else None,
            "weeks_after": round(after_d / unit_days, 1) if after_d is not None else None,
            "verdict": verdict, "recs": rec_ids}


def _sum(changes):
    d = {}
    for c in changes:
        k = (c["rack"], c["resource"])
        s = d.setdefault(k, {"level": 0.0, "slope": 0.0, "capacity": 0.0, "temporary": 0.0})
        if c.get("temporary"):
            s["temporary"] += c.get("level", 0)
        else:
            for f in ("level", "slope", "capacity"):
                s[f] += c.get(f, 0)
    return d


def evaluate(results, recs=RECOMMENDATIONS, unit_days=7):
    """Each recommendation with its live trigger status and one before/after row per change."""
    by_key = {(r["rack"], r["resource"]): r for r in results if r["fc"]}
    out = []
    for rec in recs:
        changes = [c for c in _with_temp(rec) if (c["rack"], c["resource"]) in by_key]
        rows = []
        for c in changes:
            row = _row(by_key, c["rack"], c["resource"], _sum([c])[(c["rack"], c["resource"])],
                       [rec["id"]], unit_days)
            rows.append({**row, "order": c["order"], "note": c.get("note", ""),
                         "temporary": bool(c.get("temporary"))})
        trig = by_key.get(rec["trigger"]) if rec["trigger"] else None
        out.append({**rec, "rows": rows,
                    "trigger_status": trig["status"] if trig else None})
    return out


def combined(results, ids, recs=RECOMMENDATIONS, unit_days=7):
    """Steady state with the chosen recommendations applied together, per rack × resource."""
    by_key = {(r["rack"], r["resource"]): r for r in results if r["fc"]}
    changes, who = [], {}
    for rec in recs:
        if rec["id"] in ids:
            for c in _with_temp(rec):
                if (c["rack"], c["resource"]) in by_key:
                    changes.append(c)
                    who.setdefault((c["rack"], c["resource"]), []).append(rec["id"])
    return [_row(by_key, k[0], k[1], d, sorted(set(who[k])), unit_days)
            for k, d in sorted(_sum(changes).items())]


def touching(rack, recs=RECOMMENDATIONS):
    """Ids of the recommendations that change anything on this rack (incl. side effects)."""
    return [rec["id"] for rec in recs if any(c["rack"] == rack for c in rec["changes"])]


