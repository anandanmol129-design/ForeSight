def spec_table(results, synthetic):
    """{column: {row: text}} for the Rack specs panel. Real records: the profile in use, with
    the lines that have a limit in limits.csv rewritten to that limit."""
    if synthetic:
        return RACK_SPECS
    caps = {}
    for r in results:
        caps.setdefault(r["resource"], set()).add(r["capacity"])

    def cap(res):
        lo, hi = min(caps[res]), max(caps[res])
        u = config.UNITS.get(res, "")
        return f"{lo:g} {u}" if lo == hi else f"{lo:g}–{hi:g} {u}"

    spec = dict(spec_for(None))
    lines = {"power_kw": ("Power", lambda c: f"2 × 32 A 3-phase PDUs (A/B) · {c} budget"),
             "network_gbps": ("Network", lambda c: f"ToR 2 × 50 GbE class uplinks · {c} limit"),
             "temp_c": ("Cooling", lambda c: f"Air, hot-aisle containment · {c} inlet limit"),
             "storage_tb": ("Storage", lambda c: f"{c} usable per rack")}
    row_res = {"Power": "power_kw", "Network": "network_gbps", "Cooling": "temp_c",
               "Storage": "storage_tb", "Licences": "licences"}
    for row, res in row_res.items():          # describe only what this record measures
        if res not in caps:
            spec.pop(row, None)
    for res in sorted(caps):
        if res in lines:
            row, text = lines[res]
            spec[row] = text(cap(res)) + " (limits.csv)"
        elif res in ("licences",):
            spec["Licences"] = f"{cap(res)} pool (limits.csv)"
        else:
            spec[f"Limit · {res}"] = f"{cap(res)} (limits.csv)"
    racks = sorted({r["rack"] for r in results})
    return {f"{spec['Generation']} profile · all {len(racks)} racks": spec}


def fit(rack_series):
    """Fit C_PER_KW (°C per kW: temp_c ~ power_kw) and KW_PER_VM (power_kw ~ vm_count) per
    rack with a straight line; median over racks. Returns {name: {value, fitted, r2, racks,
    default}}; value is the fit when its median R² >= MIN_R2, else the synthetic default."""
    import numpy as np
    import pandas as pd

    out = {}
    for name, x_res, y_res, default in (("C_PER_KW", "power_kw", "temp_c", C_PER_KW),
                                        ("KW_PER_VM", "vm_count", "power_kw", KW_PER_VM)):
        slopes, r2s = [], []
        for (rack, res), x in rack_series.items():
            if res != x_res or (rack, y_res) not in rack_series:
                continue
            d = pd.concat([x, rack_series[(rack, y_res)]], axis=1).dropna()
            if len(d) < 14 or d.iloc[:, 0].std() == 0:
                continue
            slopes.append(np.polyfit(d.iloc[:, 0], d.iloc[:, 1], 1)[0])
            r2s.append(np.corrcoef(d.iloc[:, 0], d.iloc[:, 1])[0, 1] ** 2)
        if slopes:
            s, r2 = float(np.median(slopes)), float(np.median(r2s))
            ok = r2 >= MIN_R2 and s > 0
            out[name] = {"value": s if ok else default, "fitted": round(s, 4),
                         "r2": round(r2, 3), "racks": len(slopes), "default": default, "used": ok}
        else:
            out[name] = {"value": default, "fitted": None, "r2": None, "racks": 0,
                         "default": default, "used": False}
    return out


def coef_text(name, c):
    """'0.15 °C/kW (synthetic default; fit on 49 racks R² 0.04 < 0.3)'."""
    unit = {"C_PER_KW": "°C/kW", "KW_PER_VM": "kW/VM"}[name]
    if c["used"]:
        return f"{c['value']:.3g} {unit} (fitted on {c['racks']} racks, median R² {c['r2']})"
    if c["racks"]:
        return (f"{c['value']:.3g} {unit} (synthetic default; this record's fit {c['fitted']:.3g} "
                f"has median R² {c['r2']} < {MIN_R2})")
    return f"{c['value']:.3g} {unit} (synthetic default; this record can't fit it)"


class _Ctx:
    def __init__(self, results, coefs, step_days):
        self.rows = [r for r in results if r["fc"]]
        self.by_key = {(r["rack"], r["resource"]): r for r in self.rows}
        self.c = coefs["C_PER_KW"]["value"]
        cf = coefs["C_PER_KW"]
        self.coef_note = (f"median R² {cf['r2']} for temperature against power"
                          if cf["r2"] is not None and not cf["used"] else "")
        self.step_days = step_days                     # real days per model day (1/24 hourly)
        self.stressed = {r["rack"] for r in self.rows if r["status"] in ("CRITICAL", "WARNING")}

    def res(self, resource):
        return [r for r in self.rows if r["resource"] == resource]

    def worst(self, resource, statuses=ALERTING):
        return sorted((r for r in self.res(resource) if r["status"] in statuses),
                      key=lambda r: (SEV_RANK[r["status"]], r["eta"]["likely"]
                                     if r["eta"]["likely"] is not None else 9e9,
                                     -r["fc"]["last_level"] / r["capacity"]))

    def get(self, rack, resource):
        return self.by_key.get((rack, resource))

    def receivers(self, resource, exclude, need=0.0):
        """Racks with the most headroom on `resource` that stay 5 % of capacity under their
        safe limit after taking `need` units and have no CRITICAL/WARNING on any resource:
        new load needs memory, power and cooling too, not only the resource being moved."""
        out = []
        for r in sorted(self.res(resource), key=lambda r: -_head(r)):
            if r["status"] != "OK" or r["rack"] in exclude or r["rack"] in self.stressed:
                continue
            if r["fc"]["last_level"] + need > r["threshold"] - 0.05 * r["capacity"]:
                continue
            t = self.get(r["rack"], "temp_c")
            if t is not None and t["status"] != "OK":
                continue
            out.append(r)
        return out


def _head(r):
    """Headroom to the safe limit as a share of capacity."""
    return (r["threshold"] - r["fc"]["last_level"]) / r["capacity"]


def _wk(r):
    return 7 * r["fc"]["slope"]


def _u(res):
    return config.UNITS.get(res, "")


def _names(rows):
    return ", ".join(r["rack"] for r in rows)


def _more(n_all, n_used):
    return (f" {n_all - n_used} more racks have the same alert; this starts with the "
            f"tightest {n_used}." if n_all > n_used else "")


def _rec(kind, group, rows, title, short, why, cost, lead, changes, risks, **extra):
    worst = min(rows, key=lambda r: SEV_RANK.get(r["status"], 3)) if rows else None
    prio = PRIORITY.get(worst["status"], "Next quarter") if worst else "Next quarter"
    return {"kind": kind, "group": group, "priority": prio,
            "trigger": (worst["rack"], worst["resource"])
            if worst and worst["status"] in ALERTING else None,
            "title": title, "short": short, "why": why, "cost": cost, "lead": lead,
            "changes": changes, "risks": risks, **extra}


