# Slope deltas are in units per week (7 model days), like the hand-written ones.

def _rule_rebalance(ctx):
    """R1-type. A growing rack: move half of the driving tenant (or, with no single driver,
    steer half of the new growth) to the OK rack with the most headroom on that resource."""
    out = []
    for res in sorted({r["resource"] for r in ctx.rows}):
        if res in ("temp_c", "power_kw", "licences"):
            continue                                  # rack-level: handled by their own rules
        hot = [r for r in ctx.worst(res) if r["fc"]["slope"] > 0]
        moves, used = [], set()
        for r in hot:
            top = r["top"]
            lvl = 0.5 * top["share_pct"] / 100 * r["fc"]["last_level"] if top and \
                top["share_pct"] >= 50 else 0.0
            sl = 0.5 * 7 * (top["slope_per_day"] if lvl else r["fc"]["slope"])
            to = ctx.receivers(res, {x["rack"] for x in hot} | used, need=lvl)
            if not to:
                continue
            used.add(to[0]["rack"])
            moves.append((r, to[0], lvl, sl, top["tenant"] if lvl else None))
            if len(moves) == MAX_RACKS:
                break
        if not moves:
            continue
        u, changes = _u(res), []
        for r, to, lvl, sl, ten in moves:
            what = f"half of {ten}'s load" if ten else "half of the new growth"
            changes += [
                {"rack": r["rack"], "resource": res, "order": 1, "level": -lvl, "slope": -sl,
                 "note": f"{what} leaves the rack"},
                {"rack": to["rack"], "resource": res, "order": 2, "level": +lvl, "slope": +sl,
                 "note": f"{to['rack']} takes {what}"}]
        pairs = "; ".join(f"{r['rack']} → {to['rack']}" for r, to, *_ in moves)
        tenant_led = any(m[4] for m in moves)
        out.append(_rec(
            "Rebalance", "Optimise", [m[0] for m in moves],
            f"{'Move half of the driving tenant' if tenant_led else 'Steer new placements'} "
            f"on {res_label(res)}: {pairs}",
            f"{res_label(res)}: move load off {len(moves)} rack(s) ({pairs})",
            f"{len(hot)} rack(s) are heading for their {res_label(res)} safe limit. "
            + ("One tenant drives most of the growth, so half of it moves "
               if tenant_led else "No single tenant drives it, so half of the new growth is "
               "placed ") + "on the OK rack with the most headroom." + _more(len(hot), len(moves)),
            "No capex · migration work", "Days",
            changes,
            ["Moving the growth also moves the problem: the receiving rack now has an ETA of "
             "its own.",
             "Services split across racks send more traffic over the spine.",
             f"Receiving racks were picked with ≥ 5 % of capacity left under the safe limit"
             + (" and an OK inlet temperature." if ctx.res("temp_c") else ".")]))
    return out


def _rule_tor(ctx):
    """R2-type. Network alert that arrives before a switch upgrade could."""
    hot = [r for r in ctx.worst("network_gbps", ("CRITICAL", "WARNING"))
           if r["eta"]["likely"] is not None
           and r["eta"]["likely"] * ctx.step_days < TOR_LEAD_DAYS + 14][:MAX_RACKS]
    if not hot:
        return []
    changes = []
    for r in hot:
        changes += [{"rack": r["rack"], "resource": "network_gbps", "order": 1,
                     "capacity": r["capacity"], "note": f"{r['capacity']:g} → "
                     f"{2 * r['capacity']:g} Gbps (2 × 50 → 2 × 100 GbE)"},
                    {"rack": r["rack"], "resource": "power_kw", "order": 2, "level": TOR_KW,
                     "note": "100G switch + 4 optics"}]
    return [_rec("Hardware upgrade", "Upgrade", hot,
                 f"Double the ToR uplinks on {_names(hot)} (2 × 50 → 2 × 100 GbE)",
                 f"{_names(hot)} ToR uplinks 2 × 50 → 2 × 100 GbE (≈$18k each, 3–5 wks)",
                 "Network reaches the safe limit sooner than optics lead time plus two weeks. "
                 "Doubling capacity is the permanent fix.",
                 f"≈ $18k per rack (switch + optics)", "3–5 weeks (optics)", changes,
                 ["The oversubscription bottleneck moves up to the spine.",
                  "During the A/B failover window there is a single uplink."])]


def _rule_storage(ctx):
    """R3/R4-type. Storage alert: a shelf (upgrade) and compression + lifecycle (optimise)."""
    hot = ctx.worst("storage_tb")[:MAX_RACKS]
    if not hot:
        return []
    n_all = len(ctx.worst("storage_tb"))
    shelf, squeeze = [], []
    for r in hot:
        add = min(SHELF_TB, r["capacity"])
        shelf += [{"rack": r["rack"], "resource": "storage_tb", "order": 1, "capacity": add,
                   "note": f"+{add:g} TB usable" + ("" if add == SHELF_TB else
                                                    " (one shelf sized to this rack)")},
                  {"rack": r["rack"], "resource": "power_kw", "order": 2, "level": SHELF_KW,
                   "note": "spinning drives + expander"},
                  {"rack": r["rack"], "resource": "network_gbps", "order": 2, "level": 8,
                   "temporary": True, "note": "cluster rebalance for ≈1 week"}]
        squeeze += [{"rack": r["rack"], "resource": "storage_tb", "order": 1,
                     "level": -0.10 * r["fc"]["last_level"], "slope": -0.25 * _wk(r),
                     "note": "assumption: −10 % now, −25 % growth (no access logs yet)"},
                    {"rack": r["rack"], "resource": "power_kw", "order": 2, "level": 0.3,
                     "note": "≈5 % more storage-node CPU for compression"}]
    return [
        _rec("Hardware upgrade", "Upgrade", hot, f"Add a JBOD shelf to {_names(hot)}",
             f"{_names(hot)} + 1 JBOD shelf (≈$14k each, 2–3 wks)",
             "Storage reaches its safe limit within the horizon." + _more(n_all, len(hot)),
             "≈ $14k per rack", "2–3 weeks", shelf,
             ["Rebuilding a failed large HDD takes 1–2 days of reduced redundancy.",
              "Uses 2U of rack space."]),
        _rec("Inefficiency", "Optimise", hot,
             f"Inline compression and a snapshot/lifecycle policy on {_names(hot)}",
             f"Compression + lifecycle policy on {_names(hot)}",
             "Cheaper than hardware and buys time. The size of the saving is an assumption "
             "until real access logs exist.",
             "No capex · needs tenants' agreement", "1–2 weeks", squeeze,
             ["Slightly higher write latency.", "Fewer restore points."])]


def _rule_licences(ctx):
    """R5-type. A licence pool running out while others sit idle: move idle seats."""
    hot = ctx.worst("licences")
    out = []
    for r in hot[:MAX_RACKS]:
        need = r["fc"]["last_level"] - r["threshold"] + 0.15 * r["capacity"]
        donors, changes = [], [{"rack": r["rack"], "resource": "licences", "order": 1,
                                "capacity": 0.0, "note": ""}]
        for d in ctx.res("licences"):
            if need <= 0 or d is r or d["fc"]["last_level"] >= 0.7 * d["capacity"]:
                continue
            give = int(min(need, d["threshold"] - d["fc"]["last_level"] - 0.1 * d["capacity"]))
            if give > 0:
                donors.append((d, give))
                need -= give
        if not donors:
            continue
        total = sum(g for _, g in donors)
        changes[0].update(capacity=total, note=f"+{total} seats")
        changes += [{"rack": d["rack"], "resource": "licences", "order": 2, "capacity": -g,
                     "note": f"−{g} seats"} for d, g in donors]
        out.append(_rec("Inefficiency", "Optimise", [r],
                        f"Reassign {total} idle licence seats to {r['rack']}",
                        f"Move {total} idle licence seats to {r['rack']}",
                        "This pool runs out first while others sit below 70 % used.",
                        "$0 if the contract allows reassignment", "Days", changes,
                        ["Donor racks lose licence headroom."]))
    return out


def _rule_stranded_power(ctx):
    """R7-type. Every rack well under its power budget: place the next GPU nodes on the rack
    with the most thermal headroom instead of building a new rack."""
    pw = ctx.res("power_kw")
    if not pw or any(r["fc"]["last_level"] >= 0.7 * r["capacity"] for r in pw):
        return []
    to = ctx.receivers("power_kw", set(), need=GPU_NODES * GPU_NODE_KW)
    to.sort(key=lambda x: -_head(t) if (t := ctx.get(x["rack"], "temp_c")) else 0)  # coolest first
    if not to:
        return []
    r, kw = to[0], GPU_NODES * GPU_NODE_KW
    used = sum(x["fc"]["last_level"] for x in pw) / sum(x["capacity"] for x in pw)
    t = ctx.get(r["rack"], "temp_c")
    changes = [{"rack": r["rack"], "resource": "power_kw", "order": 1, "level": kw,
                "note": f"{GPU_NODES} × {GPU_NODE_KW} kW GPU nodes"}]
    if ctx.get(r["rack"], "network_gbps"):
        changes.append({"rack": r["rack"], "resource": "network_gbps", "order": 2,
                        "level": GPU_INGEST_GBPS, "note": "GPU node data ingest"})
    return [_rec("Inefficiency", "Check for inefficiency", [], 
                 f"Stranded power: put the next {GPU_NODES} GPU nodes on {r['rack']} "
                 "instead of a new rack",
                 f"≈{100 * (1 - used):.0f} % of the power budget is unused: put the next "
                 f"{GPU_NODES} GPU nodes on {r['rack']}",
                 f"Racks draw {100 * used:.0f} % of their power budget on average, so "
                 f"≈{100 * (1 - used):.0f} % is paid for but unused. {r['rack']} has the most "
                 "thermal headroom" + (f" (inlet {t['fc']['last_level']:.1f} °C, safe limit "
                                       f"{t['threshold']:g} °C)." if t else "."),
                 "Saves ≈ $60k of new-rack fit-out", "With the next GPU order", changes,
                 [f"Heat follows power at {ctx.c:.2f} °C/kW; enable PDU power capping.",
                  "GPU racks need the rack-3 (GPU-ready) PDU profile."], c_per_kw=ctx.c)]


def _rule_creep(ctx):
    """R8-type. A rack total grows significantly while no tenant does: orphaned data/jobs."""
    hits = [r for r in ctx.rows if r["shares"] and r["top"] is None
            and r["fc"]["slope"] > 0.02 * r["capacity"] / 90]
    hits = sorted(hits, key=lambda r: -r["fc"]["slope"] / r["capacity"])[:MAX_RACKS]
    if not hits:
        return []
    return [_rec("Inefficiency", "Check for inefficiency", hits,
                 f"Find what grows with no tenant behind it on {_names(hits)}",
                 f"Rack totals creep with no tenant growth on {_names(hits)}: check for orphans",
                 "The rack total grows by at least 2 % of capacity per quarter while no tenant's "
                 "usage does. That is typical of stale snapshots, temp files, unrotated logs or "
                 "orphaned jobs.",
                 "No capex · 2–3 days of audit", "2 weeks",
                 [{"rack": r["rack"], "resource": r["resource"], "order": 1,
                   "level": -0.05 * r["fc"]["last_level"], "slope": -_wk(r),
                   "note": "guess: −5 % now, growth stops after cleanup"} for r in hits],
                 ["Old restore points may be lost; get each tenant to sign off."])]


def _rule_cooling(ctx):
    """Inlet temperature alerts. Check cooling when temperature rises with no rise in power;
    a rear-door heat exchanger where it is urgent; shifting load only helps by ctx.c °C/kW."""
    hot = ctx.worst("temp_c")
    if not hot:
        return []
    out = []

    coef_note = ctx.coef_note

    def power_flat(r):
        p = ctx.get(r["rack"], "power_kw")
        return p is None or p["fc"]["slope"] <= 0.02 * p["capacity"] / 90

    flat = [r for r in hot if power_flat(r)]
    out.append(_rec(
        "Inefficiency", "Check for inefficiency", hot,
        f"Check cooling and airflow on the {len(hot)} rack(s) with an inlet-temperature alert",
        f"Inlet temperature rising on {len(hot)} rack(s): check airflow and setpoints"
        + (f" ({len(flat)} with no rise in power)" if flat else ""),
        (f"On {_names(flat)} inlet temperature rises while rack power does not, so the heat "
         "comes from the room, not the rack's own load. " if flat else "")
        + "Look at the CRAC/CRAH setpoint and fan health, missing blanking panels, open "
        "containment doors, blocked floor tiles and recirculation from neighbours. "
        + (f"Rack power explains little of inlet temperature in this record "
           f"({coef_note})." if coef_note else ""),
        "No capex · 1 day walk-through", "Days",
        [{"rack": r["rack"], "resource": "temp_c", "order": 1, "slope": -_wk(r),
          "note": "assumption: once the airflow fault is fixed, the drift stops"
                  + ("" if r in flat else " (power is also rising here)")}
         for r in hot],
        ["Raising airflow raises CRAC fan power (facility side, not in rack telemetry).",
         "If the cause is a shared CRAC unit, neighbouring racks change too."],
        c_per_kw=ctx.c))
    urgent = [r for r in hot if r["status"] in ("CRITICAL", "WARNING")][:MAX_RACKS]
    if urgent:
        changes = []
        for r in urgent:
            # the door fans' own heat is folded into the temperature row (heat=False)
            changes += [{"rack": r["rack"], "resource": "temp_c", "order": 1,
                         "level": -RDHX_C + ctx.c * RDHX_KW,
                         "note": f"assumption: −{RDHX_C:g} °C from less recirculation, "
                                 f"+{ctx.c * RDHX_KW:.2f} °C from the fans"},
                        {"rack": r["rack"], "resource": "power_kw", "order": 2, "level": RDHX_KW,
                         "heat": False, "note": "door fans"}]
        out.append(_rec(
            "Hardware upgrade", "Upgrade", urgent,
            f"Fit rear-door heat exchangers on {_names(urgent)} (rack-3 profile)",
            f"Rear-door heat exchangers on {_names(urgent)} (≈$9k each, 6–8 wks)",
            "These racks reach their inlet limit soonest. A rear-door heat exchanger removes "
            "heat at the rack and cuts recirculation into the cold aisle. It takes 6–8 weeks, "
            "so the cooling check and the load shift are the stopgap."
            + _more(len([r for r in hot if r["status"] != "PLAN"]), len(urgent)),
            "≈ $9k per rack + chilled-water tap", "6–8 weeks", changes,
            ["Needs a chilled-water loop at the rack row; a leak risk above IT gear.",
             "It lowers the level once; a rising drift keeps rising (see the cooling check)."],
            c_per_kw=ctx.c))
    if ctx.res("power_kw"):
        moves, used = [], set()
        for r in hot:
            p = ctx.get(r["rack"], "power_kw")
            kw = 0.25 * p["fc"]["last_level"]
            to = ctx.receivers("power_kw", {x["rack"] for x in hot} | used, need=kw)
            to.sort(key=lambda x: -_head(t) if (t := ctx.get(x["rack"], "temp_c")) else 0)
            if not to:
                continue
            used.add(to[0]["rack"])
            moves.append((r, to[0], kw))
            if len(moves) == MAX_RACKS:
                break
        if moves:
            changes = []
            for r, to, kw in moves:
                changes += [{"rack": r["rack"], "resource": "power_kw", "order": 1, "level": -kw,
                             "note": "a quarter of the rack's jobs move out"},
                            {"rack": to["rack"], "resource": "power_kw", "order": 2, "level": kw,
                             "note": f"jobs arrive from {r['rack']}"}]
            out.append(_rec(
                "Rebalance", "Optimise", [m[0] for m in moves],
                "Move a quarter of the jobs from the hottest racks to the coolest: "
                + "; ".join(f"{r['rack']} → {to['rack']}" for r, to, _ in moves),
                f"Shift ≈25 % of load off {len(moves)} hot rack(s) to the coolest racks",
                f"Fast and free, but weak here: at {ctx.c:.2f} °C/kW, moving "
                f"{moves[0][2]:.1f} kW lowers {moves[0][0]['rack']}'s inlet by only "
                f"≈{ctx.c * moves[0][2]:.1f} °C. Use it to buy days, not as the fix.",
                "No capex · scheduler change", "Days", changes,
                ["Receiving racks warm up by the same chain (shown as their temperature rows).",
                 "Jobs pinned to specific nodes can't move."], c_per_kw=ctx.c))
    return out


def _rule_memory(ctx):
    """Memory alert with no rack to move to: upgrade host RAM (Gen-2 → Gen-3 size), and check
    for CPU stranded behind full memory."""
    hot = ctx.worst("mem_pct")
    if not hot:
        return []
    top, out = hot[:MAX_RACKS], []
    k = 1 - RAM_FROM / RAM_TO
    changes = []
    for r in top:
        changes.append({"rack": r["rack"], "resource": "mem_pct", "order": 1,
                        "level": -k * r["fc"]["last_level"], "slope": -k * _wk(r),
                        "note": f"{RAM_FROM} → {RAM_TO} GB per host: same bytes, ⅓ less of the pool"})
        if ctx.get(r["rack"], "power_kw"):
            changes.append({"rack": r["rack"], "resource": "power_kw", "order": 2,
                            "level": RAM_KW, "note": "extra DIMMs"})
    out.append(_rec(
        "Hardware upgrade", "Upgrade", top,
        f"Upgrade host RAM on {_names(top)} from {RAM_FROM} GB to {RAM_TO} GB",
        f"{_names(top)} host RAM {RAM_FROM} → {RAM_TO} GB (≈$25k per rack, 2–3 wks)",
        f"{len(hot)} rack(s) are at or near the memory safe limit"
        + (" and no rack has headroom to take load" if not ctx.receivers("mem_pct", set())
           else "") + f". Gen-3 hosts already carry {RAM_TO} GB; bringing Gen-2 hosts up to "
        f"that cuts memory use by a third." + _more(len(hot), len(top)),
        "≈ $25k per rack (DIMMs)", "2–3 weeks", changes,
        ["Each host is drained and rebooted once; plan a rolling window.",
         "Mixed DIMM sizes can lower memory bandwidth; populate channels evenly."],
        c_per_kw=ctx.c))
    idle = [r for r in hot if (c := ctx.get(r["rack"], "cpu_pct"))
            and c["fc"]["last_level"] < 0.5 * c["capacity"]]
    if idle:
        cpu = sum(ctx.get(r["rack"], "cpu_pct")["fc"]["last_level"] for r in idle) / len(idle)
        mem = sum(r["fc"]["last_level"] for r in idle) / len(idle)
        out.append(_rec(
            "Inefficiency", "Check for inefficiency", idle,
            f"Memory is full while CPU is half idle on {len(idle)} rack(s): right-size memory requests",
            f"Memory {mem:.0f} % but CPU {cpu:.0f} % on {len(idle)} rack(s): right-size memory requests",
            f"Memory averages {mem:.0f} % and CPU {cpu:.0f} % on these racks, so work is packed "
            "by memory and CPU is stranded. Memory requests are often set well above real use; "
            "right-sizing them, or placing CPU-heavy, memory-light jobs here, uses what is "
            "already paid for.",
            "No capex · needs tenants' agreement", "1–2 weeks",
            [{"rack": r["rack"], "resource": "mem_pct", "order": 1, "level": -5.0,
              "note": "guess: −5 points after right-sizing; measure before relying on it"}
             for r in idle],
            ["Requests set too tight cause out-of-memory kills; right-size from observed peaks.",
             "Packing more CPU work here raises CPU use (not modelled)."]))
    return out


RULES = [_rule_cooling, _rule_memory, _rule_tor, _rule_storage, _rule_licences,
         _rule_rebalance, _rule_stranded_power, _rule_creep]
GROUP_ORDER = {g: i for i, g in enumerate(GROUPS)}


def res_label(res):
    return {"temp_c": "temperature", "licences": "licences"}.get(res, res.split("_")[0])


def generate(results, coefs, step_days=1.0):
    """Recommendations for a real record, in the RECOMMENDATIONS shape, numbered R1… most
    urgent first. `coefs` from fit(); step_days = real days per model day."""
    ctx = _Ctx(results, coefs, step_days)
    recs = [rec for rule in RULES for rec in rule(ctx)]
    if step_days < 1:                   # hourly record: the whole horizon is days away
        for rec in recs:
            rec["priority"] = "Now" if rec["trigger"] else rec["priority"]
    recs.sort(key=lambda x: (list(PRIORITY.values()).index(x["priority"]),
                             GROUP_ORDER[x["group"]]))
    for i, rec in enumerate(recs, 1):
        rec["id"] = f"R{i}"
    return recs


def uncovered(results, recs):
    """Alerting rack × resource pairs that no recommendation changes (shown so a blank plan
    isn't mistaken for 'all fine')."""
    hit = {(c["rack"], c["resource"]) for rec in recs for c in rec["changes"]}
    return sorted((r["rack"], r["resource"]) for r in results
                  if r["status"] in ALERTING and (r["rack"], r["resource"]) not in hit)
